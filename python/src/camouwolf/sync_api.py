class Camouwolf(PlaywrightContextManager):
    """
    Wrapper around playwright.sync_api.PlaywrightContextManager that automatically
    launches a browser and closes it when the context manager is exited.
    """

    def __init__(self, **launch_options):
        super().__init__()
        self.launch_options = launch_options
        self.browser: Optional[Union[Browser, BrowserContext]] = None

    def __enter__(self) -> Union[Browser, BrowserContext]:
        super().__enter__()
        try:
            self.browser = NewBrowser(self._playwright, **self.launch_options)
        except BaseException as e:
            # Any launch failure (InvalidProxy, missing browser, bad options, ...)
            # must tear down the playwright session started above. Leaking it leaves
            # the sync API's event loop in a "running" state, so every later sync
            # Camouwolf/Playwright start in this thread fails with "Sync API inside
            # the asyncio loop" until the process restarts (#82).
            super().__exit__(type(e), e, e.__traceback__)
            raise
        return self.browser

    def __exit__(self, *args: Any):
        # Run the base teardown even if browser.close() raises (e.g. the browser
        # process already crashed). Skipping it leaks the sync API's event loop in a
        # "running" state, so every later sync Camouwolf/Playwright start in the same
        # thread fails with "Sync API inside the asyncio loop" until process restart.
        try:
            if self.browser:
                self.browser.close()
        finally:
            super().__exit__(*args)


@overload
def NewBrowser(
    playwright: Playwright,
    *,
    from_options: Optional[Dict[str, Any]] = None,
    persistent_context: Literal[False] = False,
    **kwargs,
) -> Browser: ...


@overload
def NewBrowser(
    playwright: Playwright,
    *,
    from_options: Optional[Dict[str, Any]] = None,
    persistent_context: Literal[True],
    **kwargs,
) -> BrowserContext: ...


def NewBrowser(
    playwright: Playwright,
    *,
    headless: Optional[Union[bool, Literal['virtual', 'virtual-gpu']]] = None,
    from_options: Optional[Dict[str, Any]] = None,
    persistent_context: bool = False,
    debug: Optional[bool] = None,
    **kwargs,
) -> Union[Browser, BrowserContext]:
    """
    Launches a new browser instance for Camouwolf given a set of launch options.

    Parameters:
        headless (Optional[Union[bool, Literal['virtual', 'virtual-gpu']]]):
            True for Chromium headless. On Linux, 'virtual' runs a headed browser on
            an Xvfb display, and 'virtual-gpu' on a headless Xorg server bound to
            the GPU `gpu` (or CAMOUWOLF_GPU) names; `require_gpu=False` warns instead
            of failing when the browser does not render on it.
        from_options (Dict[str, Any]):
            A set of launch options generated by `launch_options()` to use
        persistent_context (bool):
            Whether to use a persistent context.
        **kwargs:
            All other keyword arguments passed to `launch_options()`.
    """
    # humanize runs in this process: checked before the launch,
    # attached to the browser after it (also with from_options).
    _humanize_playwright.check(kwargs.get('humanize'), is_async=False)
    virtual_display, headless = start_virtual_display(headless, debug, kwargs)
    # Everything after the display exists can fail (bad proxy, missing binary,
    # unsatisfiable constraints) before sync/async_attach_vd wires kill() into
    # close, which used to strand one Xvfb and its /tmp/.X<n> lock per failed
    # launch.
    try:
        browser, os = _launch(playwright, virtual_display, headless, from_options, persistent_context, debug, kwargs)
        return _humanize_playwright.attach(
            browser, kwargs.get('humanize'), os, i_know_what_im_doing=kwargs.get('i_know_what_im_doing')
        )
    except BaseException:
        if virtual_display:
            virtual_display.kill()
        raise


def _launch(
    playwright: Playwright,
    virtual_display: Optional[VirtualDisplay],
    headless: Any,
    from_options: Optional[Dict[str, Any]],
    persistent_context: bool,
    debug: Optional[bool],
    kwargs: Dict[str, Any],
) -> Tuple[Union[Browser, BrowserContext], str]:
    """The browser (or persistent context), and its identity's OS."""
    if not from_options:
        # Opt-in. Pinning keeps the identity's core count by constraining the
        # browser to that many cores; it costs real CPU, needs a launch lock,
        # and does nothing on macOS. Off, the host's own snapped count is
        # reported, so reported and measurable still agree.
        kwargs.setdefault('pin_cpu_cores', False)
        from_options = launch_options(headless=headless, debug=debug, **kwargs)

    # Pin the driver (and so the browser it is about to spawn) to as many
    # cores as the identity reports, so measurable parallelism matches
    # navigator.hardwareConcurrency; the driver gets its cores back afterwards.
    from camoucore import cpu_affinity
    from .utils import driver_pid, pinned_core_count

    pin_to = pinned_core_count(from_options) if kwargs.get('pin_cpu_cores') else None
    pid = driver_pid(playwright) if pin_to else None
    previous = cpu_affinity.pin(pid, pin_to) if pid else None
    try:
        if persistent_context:
            context = playwright.chromium.launch_persistent_context(**persistent_context_options(from_options))
            driver_defaults.mark(context)
            return sync_attach_vd(context, virtual_display), launch_os(from_options)

        warn_addons_without_profile(from_options)
        browser = playwright.chromium.launch(**from_options)
        attach_context_defaults(browser, from_options)
        return sync_attach_vd(browser, virtual_display), launch_os(from_options)
    finally:
        if pid:
            cpu_affinity.restore(pid, previous)


def NewContext(
    browser: Browser,
    *,
    proxy: Optional[Dict[str, str]] = None,
    geolocation: Optional[Dict[str, float]] = None,
    **context_kwargs: Any,
) -> BrowserContext:
    """
    Creates a new browser context on a Camouwolf browser.

    Unlike Camoufox, a Camouwolf context has no identity of its own: the
    browser reads its identity once, per process, from the launch environment,
    and workers, request headers and the GPU process answer from it whatever a
    context emulates. So a context can differ in where it is, not in what
    machine it is.

    Parameters:
        browser: A Browser instance from NewBrowser or Camouwolf.
        proxy: Per-context proxy (Playwright format). The context is placed
            where it exits: timezone_id and geolocation default to the exit
            IP's, looked up through the proxy (needs the geoip extra) unless
            both are given; InvalidIP is raised if the lookup fails. The
            locale stays the browser's identity's.
        geolocation: Per-context geolocation ({"latitude": float, "longitude": float});
            the permission is granted with it.
        **context_kwargs: Additional Playwright new_context() options, such as
            timezone_id and locale. Options that would change the identity
            (user_agent, screen, device_scale_factor, is_mobile, has_touch) raise
            IncoherentIdentity, and Camoufox's per-context identity options
            (preset, os, ff_version, webrtc_ip) raise NotImplementedError.
    """
    geolocation, context_kwargs = place_at_exit(proxy, geolocation, context_kwargs)
    return browser.new_context(**new_context_options(context_kwargs, proxy, geolocation))
