export interface NewBrowserOptions
	extends Omit<LaunchOptions, "headless">,
		GpuDisplayOptions {
	/** True for Chromium headless. On Linux, `"virtual"` runs a headed browser
	 * on an Xvfb display, and `"virtual-gpu"` on a headless Xorg server bound
	 * to the GPU `gpu` (or CAMOUWOLF_GPU) names; `require_gpu: false` warns
	 * instead of failing when the browser does not render on it. */
	headless?: Headless;
	/** A set of launch options generated by `launchOptions()` to use as-is. */
	from_options?: Record<string, any>;
	/** Whether to use a persistent context. */
	persistent_context?: boolean;
	/** Directory for the persistent profile (Playwright's user_data_dir). */
	user_data_dir?: string;
}

/**
 * Launches a Camouwolf browser and returns it (Python: `with Camouwolf(...) as
 * browser`). Close it with `browser.close()`; a virtual display, if one was
 * spawned, is torn down with it.
 */
export async function Camouwolf(
	options: NewBrowserOptions & { persistent_context: true },
): Promise<BrowserContext>;
export async function Camouwolf(options?: NewBrowserOptions): Promise<Browser>;
export async function Camouwolf(
	options: NewBrowserOptions = {},
): Promise<Browser | BrowserContext> {
	return NewBrowser(chromium, options);
}

/**
 * Launches a new browser instance for Camouwolf given a set of launch options.
 *
 * `playwright` is Playwright's `chromium` browser type (Python passes the
 * Playwright object and reads `.chromium` from it; an object with a `chromium`
 * member is accepted too). `from_options`: a set of launch options generated
 * by `launchOptions()` to use. `persistent_context`: whether to use a
 * persistent context. Every other option is passed to `launchOptions()`.
 */
export async function NewBrowser(
	playwright: BrowserType | { chromium: BrowserType },
	options: NewBrowserOptions & { persistent_context: true },
): Promise<BrowserContext>;
export async function NewBrowser(
	playwright: BrowserType | { chromium: BrowserType },
	options?: NewBrowserOptions,
): Promise<Browser>;
export async function NewBrowser(
	playwright: BrowserType | { chromium: BrowserType },
	options: NewBrowserOptions = {},
): Promise<Browser | BrowserContext> {
	// The defaults file fills what the caller left unset; options read here
	// (headless, humanize, telemetry) need it before launchOptions runs.
	const { headless, from_options, persistent_context, debug, ...kwargs } =
		launchDefaults(options);
	const browserType: BrowserType =
		"chromium" in playwright ? playwright.chromium : playwright;
	// humanize runs in this process: checked before the launch, attached to
	// the browser after it (also with from_options).
	normalize(kwargs.humanize);
	const [virtualDisplay, headlessBool] = await startVirtualDisplay(
		headless,
		debug,
		kwargs,
	);
	// Everything after the display exists can fail (bad proxy, missing binary,
	// unsatisfiable constraints) before attachVirtualDisplay wires kill() into
	// close.
	try {
		let fromOptions = from_options;
		if (!fromOptions || !Object.keys(fromOptions).length) {
			// Opt-in. Pinning keeps the identity's core count by constraining the
			// browser to that many cores; it costs real CPU, needs a launch lock,
			// and does nothing on macOS. Off, the host's own snapped count is
			// reported, so reported and measurable still agree.
			kwargs.pin_cpu_cores ??= false;
			fromOptions = await launchOptions({
				...kwargs,
				headless: headlessBool,
				debug,
			});
		}
		const options = fromOptions;

		// Pin the driver (and so the browser it is about to spawn) to as many
		// cores as the identity reports, so measurable parallelism matches
		// navigator.hardwareConcurrency; the driver gets its cores back
		// afterwards.
		const pinTo = kwargs.pin_cpu_cores ? pinnedCoreCount(options) : null;
		const launch = () =>
			launchWith(
				browserType,
				options,
				Boolean(persistent_context),
				virtualDisplay,
				kwargs.telemetry,
			);
		let browser: Browser | BrowserContext;
		if (!pinTo) {
			browser = await cpuAffinity.withUnpinnedLaunch(launch);
		} else {
			const pid = driverPid();
			// The browser inherits the driver's mask at spawn, so two concurrent
			// launches must not interleave pin/restore.
			browser = await cpuAffinity.withPinLock(async () => {
				const previous = cpuAffinity.pin(pid, pinTo);
				try {
					return await launch();
				} finally {
					cpuAffinity.restore(pid, previous);
				}
			});
		}
		return attach(
			browser,
			kwargs.humanize,
			launchOs(options),
			kwargs.i_know_what_im_doing,
		);
	} catch (error) {
		virtualDisplay?.kill();
		throw error;
	}
}

async function launchWith(
	browserType: BrowserType,
	fromOptions: Record<string, any>,
	persistentContext: boolean,
	virtualDisplay: VirtualDisplay | null,
	telemetry: boolean | undefined,
): Promise<Browser | BrowserContext> {
	const userDataDir = fromOptions.user_data_dir ?? fromOptions.userDataDir;
	if (persistentContext) {
		// Python passes user_data_dir inside the options; the JS API takes it
		// positionally.
		const options = persistentContextOptions(fromOptions);
		delete options.user_data_dir;
		delete options.userDataDir;
		const context = await browserType.launchPersistentContext(
			userDataDir ?? "",
			options,
		);
		attachDriverDefaults(context);
		startTelemetry(context, fromOptions, telemetry, true);
		return attachVirtualDisplay(context, virtualDisplay);
	}
	if (userDataDir !== undefined) {
		// Playwright-Python refuses the keyword; playwright-core would ignore
		// it and launch a throwaway profile.
		throw new TypeError(
			"BrowserType.launch() got an unexpected keyword argument 'user_data_dir'",
		);
	}

	warnAddonsWithoutProfile(fromOptions);
	const browser = await browserType.launch(fromOptions);
	attachContextDefaults(browser, fromOptions);
	startTelemetry(browser, fromOptions, telemetry, false);
	return attachVirtualDisplay(browser, virtualDisplay);
}

export interface NewContextOptions
	extends ContextIdentityOptions,
		Record<string, any> {
	/** Per-context proxy, in Playwright's format. */
	proxy?: ProxyConfig;
	/** Per-context geolocation; the permission is granted with it. */
	geolocation?: GeolocationOption;
}

/** snake_case -> camelCase, as camouwolf.server.camel_case does. */
export function camelCase(snake: string): string {
	if (snake.length < 2) return snake;
	const parts = snake.toLowerCase().split("_");
	const joined = parts
		.map((x) => (x ? x[0].toUpperCase() + x.slice(1) : ""))
		.join("");
	return (
		(snake[0] === "_" ? "_" : "") + joined[0].toLowerCase() + joined.slice(1)
	);
}

/**
 * Creates a new browser context with an identity of its own.
 *
 * The context is another machine than the rest of the browser: its pages,
 * workers, request headers, WebRTC, GPU and fonts answer with an identity
 * drawn for it. It shares the browser's OS, screen, window and core count,
 * which one browser process cannot vary. A plain browser.newContext() keeps
 * the launch's identity.
 *
 * A `proxy` places the context where it exits: its timezone, locale, position
 * and WebRTC address are the exit IP's, looked up through the proxy (needs the
 * geoip database); InvalidIP is thrown if the lookup fails. Without one, the
 * context leaves from the browser's address and keeps its place. `os` must be
 * the launch's; `fingerprint`, `config`, `webgl_config`, `fonts` and
 * `custom_fonts_only` are as at launch, for this context; `webrtc_ip`,
 * `locale` and `timezoneId` are this context's.
 *
 * Other keys are Playwright newContext() options. Options that would make the
 * pages disagree with the identity (userAgent, screen, deviceScaleFactor,
 * isMobile, hasTouch) throw IncoherentIdentity; Camoufox's preset, ff_version
 * and chrome_version throw NotImplementedError.
 */
export async function NewContext(
	browser: Browser,
	{
		proxy,
		geolocation,
		os,
		fingerprint,
		config,
		webgl_config,
		webrtc_ip,
		fonts,
		custom_fonts_only,
		locale,
		timezoneId,
		i_know_what_im_doing,
		...contextOptions
	}: NewContextOptions = {},
): Promise<BrowserContext> {
	refuseContextOptions(contextOptions);
	const { identity, languages } = await contextIdentity(
		launchOptionsOf(browser),
		{
			proxy,
			os,
			fingerprint,
			config,
			webgl_config,
			webrtc_ip,
			fonts,
			custom_fonts_only,
			locale,
			timezoneId,
			i_know_what_im_doing,
		},
	);
	const options = newContextOptions(
		contextOptions,
		identity,
		proxy,
		geolocation,
	);
	// The new context is the one getBrowserContexts gains, and it takes its
	// identity before its first renderer.
	return serialized(browser, async () => {
		const session = await browser.newBrowserCDPSession();
		try {
			const before = await session.send("Target.getBrowserContexts");
			const context = await browser.newContext(options);
			const contextId = createdContextId(
				before,
				await session.send("Target.getBrowserContexts"),
			);
			await (session as any).send(
				"Target.setBrowserContextIdentity",
				setContextIdentityParams(contextId, identity, languages),
			);
			return context;
		} finally {
			await session.detach();
		}
	});
}

const contextQueues = new WeakMap<Browser, Promise<unknown>>();

/** Run `task` after every earlier one queued on `browser`. */
function serialized<T>(browser: Browser, task: () => Promise<T>): Promise<T> {
	const previous = contextQueues.get(browser) ?? Promise.resolve();
	const run = previous.then(task, task);
	contextQueues.set(
		browser,
		run.catch(() => undefined),
	);
	return run;
}
